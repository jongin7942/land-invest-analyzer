-- ═══════════════════════════════════════════════════════════════════════
-- 025 — 호재의 경제효과를 '비율'로 적을 수 있게 한다
-- ═══════════════════════════════════════════════════════════════════════
--
-- **왜 필요한가**
--
--   catalyst_state.economic_impact 는 원 단위 금액 하나다. 그런데 같은 역
--   앞에 3억짜리와 15억짜리가 같이 있으면, 둘에게 같은 금액을 주는 게 되어
--   말이 안 된다. 비싼 집일수록 같은 호재에서 더 큰 금액이 움직인다.
--
--   그렇다고 단지마다 금액을 따로 적을 수도 없다. catalyst_state 는 호재
--   하나의 '상태'를 적는 자리이지 단지별 표가 아니다.
--
-- **어떻게 푸는가**
--
--   측정되는 것이 애초에 금액이 아니라 **비율**이다. transit_analogue 는
--   "역세권/비역세권 대표가격 비율이 개통 전후로 몇 %p 움직였나" 를 잰다
--   (요구사항 6 이 절대 상승률을 만들지 말라고 한 이유이기도 하다).
--
--   그래서 그 비율을 그대로 적고, 단지별 금액은 읽는 시점에 만든다.
--
--       economic_impact(그 단지) = 그 단지 대표가격 × impact_ratio
--
--   `impact_ratio` 는 transit_analogue 의 delta 에서 온다. 지어낸 수가 아니라
--   이미 개통한 역에서 관측된 값이다. 어느 사례에서 왔는지는 note 에 적는다.
--
-- **기존 economic_impact 는 그대로 둔다**
--
--   금액이 정말로 확정인 호재가 있을 수 있다(예: 확정된 보상금). 그때는
--   금액을 직접 적는다. 둘 다 있으면 impact_ratio 가 이긴다 — 단지 가격에
--   맞춰 움직이는 쪽이 더 정확하기 때문이다.

ALTER TABLE catalyst_state ADD COLUMN impact_ratio REAL;

-- 비율은 '그 단지 가격의 몇 배'다. 1.0(=100%)을 넘는 호재는 현실에 없다.
-- 음수는 악재인데, 이 표는 호재만 다룬다(악재는 supply·risk 가 본다).
CREATE INDEX IF NOT EXISTS idx_catalyst_state_ratio
    ON catalyst_state (catalyst_id, as_of, impact_ratio);
